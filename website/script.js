let systemData = {
    cpu: 0,
    memory: 0,
    disk: 0,
    processes: 0,
    uptime: "Unknown",
    hostname: "Unknown"
};


/* =========================
   UPDATE DASHBOARD
========================= */

function updateDashboard() {

    document.getElementById("cpu").textContent =
        systemData.cpu + "%";

    document.getElementById("memory").textContent =
        systemData.memory + "%";

    document.getElementById("disk").textContent =
        systemData.disk + "%";

    document.getElementById("processes").textContent =
        systemData.processes;

    document.getElementById("hostname").textContent =
        systemData.hostname;

    document.getElementById("uptime").textContent =
        systemData.uptime;


    document.getElementById("cpuBar").style.width =
        systemData.cpu + "%";

    document.getElementById("memoryBar").style.width =
        systemData.memory + "%";

    document.getElementById("diskBar").style.width =
        systemData.disk + "%";


    checkAlerts();
}


/* =========================
   DIAGNOSTIC ALERTS
========================= */

function checkAlerts() {

    let alerts = [];


    /* CPU */

    if (systemData.cpu >= 90) {

        alerts.push(
            "🔴 CRITICAL: CPU usage is very high: " +
            systemData.cpu + "%"
        );

    } else if (systemData.cpu >= 80) {

        alerts.push(
            "⚠ WARNING: CPU usage is high: " +
            systemData.cpu + "%"
        );

    } else {

        alerts.push(
            "✓ NORMAL: CPU usage: " +
            systemData.cpu + "%"
        );
    }


    /* MEMORY */

    if (systemData.memory >= 90) {

        alerts.push(
            "🔴 CRITICAL: Memory usage is very high: " +
            systemData.memory + "%"
        );

    } else if (systemData.memory >= 80) {

        alerts.push(
            "⚠ WARNING: Memory usage is high: " +
            systemData.memory + "%"
        );

    } else {

        alerts.push(
            "✓ NORMAL: Memory usage: " +
            systemData.memory + "%"
        );
    }


    /* DISK */

    if (systemData.disk >= 90) {

        alerts.push(
            "🔴 CRITICAL: Disk usage is very high: " +
            systemData.disk + "%"
        );

    } else if (systemData.disk >= 80) {

        alerts.push(
            "⚠ WARNING: Disk usage is high: " +
            systemData.disk + "%"
        );

    } else {

        alerts.push(
            "✓ NORMAL: Disk usage: " +
            systemData.disk + "%"
        );
    }


    /* PROCESSES */

    if (systemData.processes >= 300) {

        alerts.push(
            "⚠ WARNING: Large number of processes: " +
            systemData.processes
        );

    } else {

        alerts.push(
            "✓ NORMAL: Running processes: " +
            systemData.processes
        );
    }


    document.getElementById("alerts").innerHTML =
        alerts.join("<br><br>");
}


/* =========================
   DEMO SYSTEM DATA
========================= */

function refreshData() {

    /*
       Temporary demonstration values.
       Later these will come from diagnostics.c
    */

    systemData.cpu =
        Math.floor(Math.random() * 100);

    systemData.memory =
        Math.floor(Math.random() * 100);

    systemData.disk =
        Math.floor(Math.random() * 100);

    systemData.processes =
        Math.floor(Math.random() * 250) + 100;

    systemData.uptime =
        "5h 23m";

    systemData.hostname =
        "Ubuntu";


    updateDashboard();
}


/* =========================
   REPORT
========================= */

function generateReport() {

    let report =
        "========================================\n" +
        "       LINUX DIAGNOSTIC REPORT\n" +
        "========================================\n\n" +

        "Hostname       : " +
        systemData.hostname + "\n" +

        "CPU Usage      : " +
        systemData.cpu + "%\n" +

        "Memory Usage   : " +
        systemData.memory + "%\n" +

        "Disk Usage     : " +
        systemData.disk + "%\n" +

        "Processes      : " +
        systemData.processes + "\n" +

        "System Uptime  : " +
        systemData.uptime + "\n\n" +

        "========================================\n" +
        "Generated by Linux System Diagnostics\n" +
        "========================================\n";


    let blob = new Blob(
        [report],
        { type: "text/plain" }
    );


    let link = document.createElement("a");

    link.href =
        URL.createObjectURL(blob);

    link.download =
        "diagnostic_report.txt";

    link.click();
}


/* =========================
   START APPLICATION
========================= */

document.addEventListener(
    "DOMContentLoaded",
    function () {

        refreshData();

    }
);
